export type MessageKey = keyof typeof zh;

/* ------------------------------------------------------------------ */
/* locale 状态（模块级，供 React 与非 React 代码共用）                  */
/* ------------------------------------------------------------------ */

function readInitialLocale(): Locale {
  try { return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "zh"; } catch { return "zh"; }
}

let locale: Locale = readInitialLocale();
const listeners = new Set<() => void>();

export function getLocale(): Locale { return locale; }

/** 切换界面语言；localStorage 仅作首屏加速，权威来源是 AppConfig.language */
export function setLocale(next: Locale): void {
  if (locale === next) return;
  locale = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* 非浏览器环境忽略 */ }
  for (const listener of listeners) listener();
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}

/** 按指定 locale 查文案（缺失键回退中文），{var} 占位替换 */
export function formatMessage(locale_: Locale, key: MessageKey, vars?: Vars): string {
  const template = (locale_ === "en" ? en : zh)[key] ?? zh[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ""));
}

/** React hook：返回当前语言与绑定的 t() */
export function useI18n(): { locale: Locale; t: (key: MessageKey, vars?: Vars) => string } {
  const current = useSyncExternalStore(subscribe, getLocale);
  return useMemo(() => ({
    locale: current,
    t: (key: MessageKey, vars?: Vars): string => formatMessage(current, key, vars),
  }), [current]);
}
